#!/usr/bin/env node

/**
 * Icon Subset
 *
 * Writes src/styles/icons/: a Font Awesome stylesheet with only the icon
 * classes the site uses, and the three Font Awesome fonts cut down to those
 * glyphs. The full package shipped about 300 KB of fonts and 74 KB of CSS
 * for roughly a hundred icons.
 *
 * The markup keeps its class names (`fas fa-check`), so nothing else changes.
 * Adding an icon means running this again; tests/icons.test.ts fails until
 * the committed stylesheet covers every class in the source.
 *
 * Usage:
 *   npm run generate:icons
 */

import fs from 'fs';
import { createRequire } from 'module';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ROOT = path.join(__dirname, '..');
const FA_DIR = path.dirname(
  path.dirname(
    createRequire(import.meta.url).resolve('@fortawesome/fontawesome-free/css/all.min.css'),
  ),
);
/** Font Awesome's full stylesheet, the input of the subset. */
export const FA_CSS_PATH = path.join(FA_DIR, 'css/all.min.css');
export const OUTPUT_DIR = path.join(ROOT, 'src/styles/icons');

// Where icon class names can appear: markup, data, and translations.
const SOURCE_DIRS = ['components', 'src', 'public/locales'];
const SOURCE_FILES = ['App.tsx', 'constants.tsx', 'index.tsx', 'index.html'];
const SOURCE_EXTENSIONS = new Set(['.ts', '.tsx', '.json', '.html']);

const FONTS = [
  { file: 'fa-solid-900', family: 'Font Awesome 6 Free', weight: 900 },
  { file: 'fa-regular-400', family: 'Font Awesome 6 Free', weight: 400 },
  { file: 'fa-brands-400', family: 'Font Awesome 6 Brands', weight: 400 },
];

function listSourceFiles(root) {
  const walk = (dir) =>
    fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return full === OUTPUT_DIR ? [] : walk(full);
      return SOURCE_EXTENSIONS.has(path.extname(entry.name)) ? [full] : [];
    });
  return [
    ...SOURCE_DIRS.map((dir) => path.join(root, dir))
      .filter((dir) => fs.existsSync(dir))
      .flatMap(walk),
    ...SOURCE_FILES.map((file) => path.join(root, file)).filter((file) => fs.existsSync(file)),
  ];
}

/** Every `fa-…` class name in the source, sorted. */
export function usedIconClasses(root = ROOT) {
  const found = new Set();
  for (const file of listSourceFiles(root)) {
    for (const [name] of fs.readFileSync(file, 'utf8').matchAll(/\bfa-[a-z0-9]+(?:-[a-z0-9]+)*/g)) {
      found.add(name);
    }
  }
  return [...found].sort();
}

/** Top-level statements of a stylesheet, keeping nested blocks (@keyframes, @media) whole. */
function splitStatements(css) {
  const statements = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < css.length; i += 1) {
    if (css[i] === '{') depth += 1;
    if (css[i] === '}') {
      depth -= 1;
      if (depth === 0) {
        statements.push(css.slice(start, i + 1).trim());
        start = i + 1;
      }
    }
  }
  return statements.filter(Boolean);
}

const ICON_RULE = /^([^{]+)\{--fa:"([^"]+)"\}$/;

/** The code point of a CSS content value such as `\f058` or `\30 `. */
function codePoint(value) {
  const escaped = value.match(/^\\([0-9a-f]+)\s?$/i);
  return escaped ? parseInt(escaped[1], 16) : value.codePointAt(0);
}

/**
 * The stylesheet for `used`: Font Awesome's base and utility rules, the icon
 * rules for used classes only, and @font-face rules for the subset fonts.
 * Also returns the code points those icons need.
 */
export function buildIconCss(faCss, used) {
  const wanted = new Set(used);
  const codePoints = new Set();
  const kept = [];
  for (const statement of splitStatements(faCss.replace(/\/\*[\s\S]*?\*\//g, ''))) {
    if (statement.startsWith('@font-face')) continue;
    const icon = statement.match(ICON_RULE);
    if (!icon) {
      kept.push(statement);
      continue;
    }
    const selectors = icon[1].split(',').filter((selector) => wanted.has(selector.slice(1)));
    if (selectors.length === 0) continue;
    codePoints.add(codePoint(icon[2]));
    kept.push(`${selectors.join(',')}{--fa:"${icon[2]}"}`);
  }
  const faces = FONTS.map(
    ({ file, family, weight }) =>
      `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:block;src:url(./${file}.woff2) format("woff2")}`,
  );
  const header =
    '/* Generated by scripts/subset-icons.js from Font Awesome Free (Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT). Do not edit. */';
  return {
    css: `${[header, ...faces, ...kept].join('\n')}\n`,
    codePoints: [...codePoints].sort((a, b) => a - b),
  };
}

export async function writeIcons() {
  const subsetFont = (await import('subset-font')).default;
  const faCss = fs.readFileSync(FA_CSS_PATH, 'utf8');
  const used = usedIconClasses();
  const { css, codePoints } = buildIconCss(faCss, used);
  const text = String.fromCodePoint(...codePoints);

  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUTPUT_DIR, 'icons.css'), css);
  const sizes = [];
  for (const { file } of FONTS) {
    const source = fs.readFileSync(path.join(FA_DIR, `webfonts/${file}.ttf`));
    const subset = await subsetFont(source, text, { targetFormat: 'woff2' });
    fs.writeFileSync(path.join(OUTPUT_DIR, `${file}.woff2`), subset);
    sizes.push(`${file} ${(subset.length / 1024).toFixed(1)} KB`);
  }
  return { icons: codePoints.length, classes: used.length, sizes };
}

async function main() {
  try {
    const { icons, classes, sizes } = await writeIcons();
    console.log(`🔣 icons: ${classes} classes, ${icons} glyphs; ${sizes.join(', ')}`);
  } catch (error) {
    console.error('❌ Error subsetting icons:', error.message);
    process.exit(1);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
